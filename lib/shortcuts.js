/**
 * Shortcut generation for the three desktop platforms.
 *
 * Every target ends up running `lib/launcher.cjs` with a `launcher.json`
 * config sitting next to it, so the OS-specific work is only the wrapper:
 *
 *   macOS  -> a real `.app` bundle (Finder icon, Dock, double-click)
 *   Windows-> `%LOCALAPPDATA%\dsh-one-click-launcher` + a `.lnk` on the desktop
 *            whose target is `wscript.exe` running a VBS shim (no console flash)
 *   Linux  -> a `.desktop` entry on the desktop plus one in the app menu
 *
 * All file contents are generated as text: no shell interpolation and no
 * platform-specific binaries beyond the launcher script itself.
 */
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import { APP_NAME, APP_SLUG, desktopQuote, vbsString, xmlEscape } from './platforms.js';

export const LAUNCHER_SCRIPT = 'launcher.cjs';
export const LAUNCHER_CONFIG = 'launcher.json';

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}

function writeFile(file, content, mode) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf8');
  if (mode !== undefined) fs.chmodSync(file, mode);
  return file;
}

function removeTree(target) {
  fs.rmSync(target, { recursive: true, force: true });
}

/** Launcher config handed to lib/launcher.cjs. */
export function launcherConfig({ appName, port, profile, cwd, command }) {
  return {
    schema: 1,
    appName,
    port,
    profile,
    cwd,
    command: command || null,
    fallback: { file: 'dsh', args: [profile, '--no-open', '--port', String(port)] },
  };
}

/** Copy the shared payload (launcher.cjs + launcher.json) into `dir`. */
function writePayload(dir, { launcherSource, config }) {
  ensureDir(dir);
  fs.copyFileSync(launcherSource, path.join(dir, LAUNCHER_SCRIPT));
  writeFile(path.join(dir, LAUNCHER_CONFIG), JSON.stringify(config, null, 2) + '\n');
  return dir;
}

/** Canonical launcher payload shipped with this package (lib/launcher.cjs). */
export function defaultLauncherSource() {
  return path.join(path.dirname(fileURLToPath(import.meta.url)), LAUNCHER_SCRIPT);
}

// ---- macOS ---------------------------------------------------------------

export function macBundlePaths(desktop, appName = APP_NAME) {
  const bundle = path.join(desktop, appName + '.app');
  const contents = path.join(bundle, 'Contents');
  const resources = path.join(contents, 'Resources');
  return {
    bundle,
    contents,
    resources,
    executable: path.join(contents, 'MacOS', 'DSHWeb'),
    plist: path.join(contents, 'Info.plist'),
    pkgInfo: path.join(contents, 'PkgInfo'),
    icon: path.join(resources, 'AppIcon.icns'),
  };
}

export function macInfoPlist(appName = APP_NAME) {
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n' +
    '<plist version="1.0">\n' +
    '<dict>\n' +
    '\t<key>CFBundleName</key>\n\t<string>' + xmlEscape(appName) + '</string>\n' +
    '\t<key>CFBundleDisplayName</key>\n\t<string>' + xmlEscape(appName) + '</string>\n' +
    '\t<key>CFBundleIdentifier</key>\n\t<string>local.' + APP_SLUG + '</string>\n' +
    '\t<key>CFBundleVersion</key>\n\t<string>1.0</string>\n' +
    '\t<key>CFBundleShortVersionString</key>\n\t<string>1.0</string>\n' +
    '\t<key>CFBundleInfoDictionaryVersion</key>\n\t<string>6.0</string>\n' +
    '\t<key>CFBundlePackageType</key>\n\t<string>APPL</string>\n' +
    '\t<key>CFBundleSignature</key>\n\t<string>????</string>\n' +
    '\t<key>CFBundleExecutable</key>\n\t<string>DSHWeb</string>\n' +
    '\t<key>CFBundleIconFile</key>\n\t<string>AppIcon</string>\n' +
    '\t<key>LSMinimumSystemVersion</key>\n\t<string>11.0</string>\n' +
    '\t<key>LSApplicationCategoryType</key>\n\t<string>public.app-category.developer-tools</string>\n' +
    '\t<key>NSHighResolutionCapable</key>\n\t<true/>\n' +
    '\t<key>NSPrincipalClass</key>\n\t<string>NSApplication</string>\n' +
    '</dict>\n</plist>\n';
}

export function macShellStub(nodePath) {
  const node = nodePath ? JSON.stringify(nodePath) : '""';
  return '#!/bin/bash\n' +
    '# Generated by ' + APP_SLUG + '. Starts DSH through the bundled launcher payload.\n' +
    'set -u\n' +
    'DIR="$(cd "$(dirname "$0")/../Resources" && pwd)"\n' +
    '\n' +
    'PATH="/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin:$PATH"\n' +
    'NODE=' + node + '\n' +
    'if [ -z "$NODE" ] || [ ! -x "$NODE" ]; then\n' +
    '  NODE="$(command -v node || true)"\n' +
    'fi\n' +
    'if [ -z "$NODE" ]; then\n' +
    "  /usr/bin/osascript -e 'display alert \"DSH Web\" message \"找不到 Node.js，无法启动 DSH Web。\" as warning' >/dev/null 2>&1\n" +
    '  exit 1\n' +
    'fi\n' +
    '\n' +
    'exec "$NODE" "$DIR/launcher.cjs" "$DIR/launcher.json"\n';
}

function createMac({ desktop, assetsDir, launcherSource, config, appName }) {
  const p = macBundlePaths(desktop, appName);
  removeTree(p.bundle);
  ensureDir(p.resources);
  ensureDir(path.dirname(p.executable));
  writeFile(p.plist, macInfoPlist(appName));
  writeFile(p.pkgInfo, 'APPL????');
  writeFile(p.executable, macShellStub(config.command && config.command.file), 0o755);
  fs.copyFileSync(path.join(assetsDir, 'icon.icns'), p.icon);
  writePayload(p.resources, { launcherSource, config });
  try {
    fs.utimesSync(p.bundle, new Date(), new Date());
  } catch {
    /* Finder icon refresh is best effort */
  }
  return { path: p.bundle, extras: [], kind: 'app-bundle' };
}

// ---- Windows -------------------------------------------------------------

export function winPaths(desktop, installDir, appName = APP_NAME) {
  return {
    dir: installDir,
    vbs: path.join(installDir, 'launch.vbs'),
    icon: path.join(installDir, 'icon.ico'),
    lnk: path.join(desktop, appName + '.lnk'),
    cmd: path.join(desktop, appName + '.cmd'),
  };
}

export function winVbsScript(nodePath, dir, cwd) {
  return "' Generated by " + APP_SLUG + '. Runs the launcher without a console window.\n' +
    'Option Explicit\n' +
    'Dim shell, fso, node, scriptPath, configPath\n' +
    'Set shell = CreateObject("WScript.Shell")\n' +
    'Set fso = CreateObject("Scripting.FileSystemObject")\n' +
    'node = "' + vbsString(nodePath || '') + '"\n' +
    'If Not fso.FileExists(node) Then node = "node.exe"\n' +
    'scriptPath = "' + vbsString(path.join(dir, LAUNCHER_SCRIPT)) + '"\n' +
    'configPath = "' + vbsString(path.join(dir, LAUNCHER_CONFIG)) + '"\n' +
    'If Not fso.FileExists(scriptPath) Then\n' +
    '  MsgBox "找不到启动脚本：" & scriptPath, 48, "DSH Web"\n' +
    '  WScript.Quit 1\n' +
    'End If\n' +
    'shell.CurrentDirectory = "' + vbsString(cwd) + '"\n' +
    'shell.Run """" & node & """ """ & scriptPath & """ """ & configPath & """", 0, False\n';
}

export function winCmdScript(nodePath, dir) {
  const node = nodePath || 'node';
  return [
    '@echo off',
    'rem Generated by ' + APP_SLUG + '. Fallback launcher used when .lnk creation fails.',
    'set "NODE=' + node + '"',
    'if not exist "%NODE%" set "NODE=node"',
    'start "" /b "%NODE%" "' + path.join(dir, LAUNCHER_SCRIPT) + '" "' + path.join(dir, LAUNCHER_CONFIG) + '"',
    '',
  ].join('\r\n');
}

/** PowerShell script that writes the .lnk through WScript.Shell. */
export function winShortcutPowerShell({ lnk, vbs, icon, workingDirectory, description, wscript }) {
  const q = (value) => "'" + String(value).replace(/'/g, "''") + "'";
  return [
    '$ErrorActionPreference = "Stop"',
    '$ws = New-Object -ComObject WScript.Shell',
    '$s = $ws.CreateShortcut(' + q(lnk) + ')',
    '$s.TargetPath = ' + q(wscript),
    '$s.Arguments = ' + q('"' + vbs + '"'),
    '$s.WorkingDirectory = ' + q(workingDirectory),
    '$s.IconLocation = ' + q(icon + ',0'),
    '$s.Description = ' + q(description),
    '$s.Save()',
  ].join('\n');
}

export function defaultRunPowerShell(script) {
  const result = spawnSync(
    'powershell',
    ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', script],
    { encoding: 'utf8', windowsHide: true, timeout: 30000 },
  );
  return { ok: result.status === 0, stderr: String(result.stderr || '') };
}

function createWindows({ desktop, installDir, assetsDir, launcherSource, config, appName, runPowerShell }) {
  const p = winPaths(desktop, installDir, appName);
  ensureDir(p.dir);
  const nodePath = config.command && config.command.file ? config.command.file : '';
  writeFile(p.vbs, winVbsScript(nodePath, p.dir, config.cwd), 0o644);
  writeFile(p.cmd, winCmdScript(nodePath, p.dir), 0o644);
  fs.copyFileSync(path.join(assetsDir, 'icon.ico'), p.icon);
  writePayload(p.dir, { launcherSource, config });

  const wscript = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'wscript.exe');
  const script = winShortcutPowerShell({
    lnk: p.lnk,
    vbs: p.vbs,
    icon: p.icon,
    workingDirectory: config.cwd,
    description: appName + ' — one-click DeepSeek Harness launcher',
    wscript,
  });
  const result = runPowerShell(script);
  if (!result.ok) {
    const detail = result.stderr.trim().split('\n').filter(Boolean).slice(-1)[0] || 'PowerShell 不可用';
    return {
      path: p.cmd,
      extras: [p.vbs],
      kind: 'cmd-fallback',
      warning: '无法创建 .lnk（' + detail + '），已在桌面生成 .cmd 备用入口。',
    };
  }
  return { path: p.lnk, extras: [p.vbs, p.cmd], kind: 'lnk' };
}

// ---- Linux ---------------------------------------------------------------

export function linuxPaths(desktop, installDir, applicationsDir, appName = APP_NAME) {
  return {
    dir: installDir,
    shell: path.join(installDir, 'launch.sh'),
    icon: path.join(installDir, 'icon.png'),
    entry: path.join(desktop, appName + '.desktop'),
    appEntry: applicationsDir ? path.join(applicationsDir, APP_SLUG + '.desktop') : null,
  };
}

export function linuxShellStub(nodePath) {
  const node = nodePath ? JSON.stringify(nodePath) : '""';
  return '#!/bin/sh\n' +
    '# Generated by ' + APP_SLUG + '. Starts DSH through the bundled launcher payload.\n' +
    'set -u\n' +
    'DIR="$(cd "$(dirname "$0")" && pwd)"\n' +
    'NODE=' + node + '\n' +
    'if [ -z "$NODE" ] || [ ! -x "$NODE" ]; then\n' +
    '  NODE="$(command -v node || true)"\n' +
    'fi\n' +
    'if [ -z "$NODE" ]; then\n' +
    '  command -v zenity >/dev/null 2>&1 && zenity --error --title="DSH Web" --text="找不到 Node.js，无法启动 DSH Web。"\n' +
    '  exit 1\n' +
    'fi\n' +
    'exec "$NODE" "$DIR/launcher.cjs" "$DIR/launcher.json"\n';
}

export function linuxDesktopEntry({ appName, shell, icon, cwd }) {
  return [
    '[Desktop Entry]',
    'Version=1.0',
    'Type=Application',
    'Name=' + appName,
    'Comment=启动 DeepSeek Harness Web GUI（一键启动）',
    'Exec=' + desktopQuote(shell),
    'Path=' + cwd,
    'Icon=' + icon,
    'Terminal=false',
    'Categories=Development;',
    'StartupNotify=false',
    '',
  ].join('\n');
}

function createLinux({ desktop, installDir, applicationsDir, assetsDir, launcherSource, config, appName }) {
  const p = linuxPaths(desktop, installDir, applicationsDir, appName);
  ensureDir(p.dir);
  const nodePath = config.command && config.command.file ? config.command.file : '';
  writeFile(p.shell, linuxShellStub(nodePath), 0o755);
  fs.copyFileSync(path.join(assetsDir, 'icon.png'), p.icon);
  writePayload(p.dir, { launcherSource, config });

  const entry = linuxDesktopEntry({ appName, shell: p.shell, icon: p.icon, cwd: config.cwd });
  writeFile(p.entry, entry, 0o755);
  const extras = [];
  if (p.appEntry) {
    writeFile(p.appEntry, entry, 0o644);
    extras.push(p.appEntry);
  }
  try {
    // GNOME only launches desktop files marked trusted; harmless elsewhere.
    spawnSync('gio', ['set', p.entry, 'metadata::trusted', 'true'], { stdio: 'ignore', timeout: 3000 });
  } catch {
    /* best effort */
  }
  return { path: p.entry, extras, kind: 'desktop-entry' };
}

// ---- public API ----------------------------------------------------------

/**
 * Create (or replace) the desktop shortcut for `platform`.
 * @returns {{ path: string, extras: string[], kind: string, warning?: string }}
 */
export function createShortcut(options) {
  const {
    platform,
    desktop,
    installDir,
    applicationsDir = null,
    assetsDir,
    port,
    profile,
    cwd,
    command = null,
    appName = APP_NAME,
    launcherSource = defaultLauncherSource(),
    runPowerShell = defaultRunPowerShell,
  } = options;
  if (!platform) throw new Error('createShortcut: platform is required');
  if (!desktop) throw new Error('createShortcut: desktop is required');
  if (!assetsDir) throw new Error('createShortcut: assetsDir is required');
  ensureDir(desktop);
  const config = launcherConfig({ appName, port, profile, cwd, command });
  if (platform === 'darwin') return createMac({ desktop, assetsDir, launcherSource, config, appName });
  if (platform === 'win32') {
    if (!installDir) throw new Error('createShortcut: installDir is required on Windows');
    return createWindows({ desktop, installDir, assetsDir, launcherSource, config, appName, runPowerShell });
  }
  if (!installDir) throw new Error('createShortcut: installDir is required on Linux');
  return createLinux({ desktop, installDir, applicationsDir, assetsDir, launcherSource, config, appName });
}

/** Path of the shortcut that createShortcut() would produce / has produced. */
export function shortcutPath({ platform, desktop, appName = APP_NAME }) {
  if (platform === 'darwin') return path.join(desktop, appName + '.app');
  if (platform === 'win32') {
    const lnk = path.join(desktop, appName + '.lnk');
    const cmd = path.join(desktop, appName + '.cmd');
    return !fs.existsSync(cmd) || fs.existsSync(lnk) ? lnk : cmd;
  }
  return path.join(desktop, appName + '.desktop');
}

/** Remove the shortcut and the launcher payload it points at. */
export function removeShortcut({ platform, desktop, installDir, applicationsDir = null, appName = APP_NAME }) {
  const targets = [];
  if (platform === 'darwin') {
    targets.push(path.join(desktop, appName + '.app'));
  } else if (platform === 'win32') {
    targets.push(path.join(desktop, appName + '.lnk'), path.join(desktop, appName + '.cmd'), installDir);
  } else {
    targets.push(path.join(desktop, appName + '.desktop'));
    if (applicationsDir) targets.push(path.join(applicationsDir, APP_SLUG + '.desktop'));
    targets.push(installDir);
  }
  const removed = [];
  for (const target of targets) {
    if (!target || !fs.existsSync(target)) continue;
    removeTree(target);
    removed.push(target);
  }
  return removed;
}
